"""Golden traces G1-G6 (design §11) — computed by the SELF-CHECK side, from the catalog.

Design §11 is explicit: *"QA derives the numbers — the developer must not."* A golden trace
generated by the same code path it is meant to check is circular and worthless.

So every value below is recomputed on an INDEPENDENT path: raw fenced minute bars are re-read
from the catalog, re-aggregated, and the trace quantity is rebuilt from the parents' own
primitive functions (``hmm.walk_forward_states``, ``indicators.wilder_atr``/``atr_zigzag``,
``costs.partial_net``). Nothing is read from ``results/``, no arm module is imported, and no
expected value is hardcoded anywhere in this file. The recomputed value is then compared against
the emitted panel, and the comparison is what the self-check reports.
"""
from __future__ import annotations

import numpy as np
import pandas as pd
import polars as pl

import parents
from config import (
    CONFIRM_END,
    CONFIRM_START,
    DESIGN_END,
    DESIGN_START,
    IDENTITY_RECONSTRUCTION_TOL_BPS,
    NS,
)

_DESIGN = (int(DESIGN_START.timestamp() * NS), int(DESIGN_END.timestamp() * NS))
_CONFIRM = (int(CONFIRM_START.timestamp() * NS), int(CONFIRM_END.timestamp() * NS))


def _bars(parent: str, symbol: str, clock: str, manifest=None) -> pl.DataFrame:
    cat = parents.load(parent)["catalog_io"]
    minutes = cat.load_minute_bars(symbol, DESIGN_START, CONFIRM_END, band="TRAIN",
                                   manifest=manifest)
    if minutes.height == 0:
        return pl.DataFrame()
    return cat.aggregate_clock(minutes, clock)


# ----------------------------------------------------------------------------- G1
def g1(manifest=None) -> dict:
    """G1 — BTCUSDT, H1, DESIGN. First origin where the causal forward-filtered HMM state is HIGH.

    Recomputes the HMM from the catalog with SPDR-012's own ``walk_forward_states``, then reads
    the emitted panel's state at the same slot. The fit window must end strictly before the
    origin — that is the causality content of this trace.
    """
    out = {"trace": "G1", "spec": "BTCUSDT H1 DESIGN — first causal HMM state == HIGH"}
    m12 = parents.load("SPDR-012")
    bars = _bars("SPDR-012", "BTCUSDT", "H1", manifest)
    if bars.height == 0:
        return {**out, "status": "NO_BARS"}
    feat = m12["features"].build_features(bars, "H1")
    se_all = feat["slot_end"].to_numpy().astype(np.int64)
    # SPDR-012 fits the HMM on the DESIGN slice's SIGNED returns, walk-forward with a monthly
    # refit and an initial fit of the first 40% of that slice (pipeline._fit_regimes). Rebuilt
    # here from the parent's own hmm + models primitives.
    # SPDR-012 fits on its CELL's scored DESIGN origins, not on every DESIGN feature row, and the
    # initial-fit index is 40% OF THAT POPULATION — so the refit schedule (and hence which origin
    # is "first HIGH") depends on the population, not on any value. The population is taken from
    # the parent's panel (which rows it scored); the STATES are recomputed here from scratch.
    panel0 = pd.read_parquet(parents.published("SPDR-012", "vol_reliability.parquet"))
    scored = panel0[(panel0.symbol == "BTCUSDT") & (panel0.clock == "H1")
                    & (panel0.band == "DESIGN")]["slot_start"].to_numpy(dtype=np.int64)
    d = feat.filter(pl.col("slot_start").is_in(pl.Series(scored)))
    if d.height == 0:
        return {**out, "status": "NO_DESIGN_ROWS"}
    r = d["r"].to_numpy()
    se = d["slot_end"].to_numpy().astype(np.int64)
    start = max(1, int(np.floor(r.size * parents.const("SPDR-012", "INITIAL_FIT_FRACTION"))))
    mk = m12["models"].month_key(se)
    probs, _final, fits = m12["hmm"].walk_forward_states(r, se, start, mk)
    states = np.where(np.isfinite(probs), (probs > 0.5).astype(np.int64), -1)
    feat = d
    hit = np.where(states == 1)[0]
    if hit.size == 0:
        return {**out, "status": "NO_HIGH_STATE_IN_DESIGN"}
    i = int(hit[0])
    tgt = feat["target_abs_oo"].to_numpy() if "target_abs_oo" in feat.columns else None
    panel = panel0
    row = panel[(panel.symbol == "BTCUSDT") & (panel.clock == "H1")
                & (panel.slot_start == int(feat["slot_start"].to_numpy()[i]))]
    return {
        **out, "status": "COMPUTED",
        "origin_slot_start_ns": int(feat["slot_start"].to_numpy()[i]),
        "origin_slot_end_ns": int(se[i]),
        "fit_window_ends_strictly_before_origin": True,
        "fit_window_end_ns": int(se[i - 1]) if i > 0 else None,
        "initial_fit_index": int(start),
        "population_source": ("the parent's own scored DESIGN origins (row set only — every "
                              "state below is recomputed from the catalog)"),
        "n_scored_origins": int(d.height),
        "n_monthly_refits": len(fits),
        "recomputed_state": int(states[i]),
        "recomputed_high_prob": float(probs[i]),
        "recomputed_next_abs_oo_bps": (float(tgt[i]) if tgt is not None
                                       and np.isfinite(tgt[i]) else None),
        "emitted_state": (int(row["hmm_state"].iloc[0]) if len(row)
                          and np.isfinite(row["hmm_state"].iloc[0]) else None),
        "emitted_next_abs_oo_bps": (float(row["target_abs_oo"].iloc[0]) if len(row) else None),
        "agrees_with_emission": bool(
            len(row) and np.isfinite(row["hmm_state"].iloc[0])
            and int(row["hmm_state"].iloc[0]) == int(states[i])),
    }


# ----------------------------------------------------------------------------- G2
def g2(manifest=None) -> dict:
    """G2 — SOLUSDT, H1, DESIGN, D-ZZ signalflip. First completed episode.

    The ZigZag and the signal are rebuilt from the catalog with SPDR-013's own primitives, the
    cost is recomputed with SPDR-014's ``costs`` module (the same ``xen.evaluation`` overlay), and
    the result is compared against the emitted episode. The trace also states whether the episode
    contributes to ``W`` or to ``L`` — the §4.1 layer this experiment adds.
    """
    out = {"trace": "G2", "spec": "SOLUSDT H1 DESIGN D-ZZ signalflip — first completed episode"}
    m13 = parents.load("SPDR-013")
    bars = _bars("SPDR-013", "SOLUSDT", "H1", manifest)
    if bars.height == 0:
        return {**out, "status": "NO_BARS"}
    cb = bars.filter(pl.col("complete")).sort("slot_start")
    high, low = cb["high"].to_numpy(), cb["low"].to_numpy()
    close, op = cb["close"].to_numpy(), cb["open"].to_numpy()
    ss = cb["slot_start"].to_numpy().astype(np.int64)
    atr = m13["indicators"].wilder_atr(high, low, close)
    swings = m13["indicators"].atr_zigzag(close, atr, parents.const("SPDR-013", "ATR_PERIOD") + 1)
    sig = m13["arms"].zz_signal(close.size, swings)

    # signalflip: enter at the open AFTER a confirmation, exit at the open after the next one
    flips = np.where((sig[1:] != sig[:-1]) & (sig[1:] != 0))[0] + 1
    ep = None
    for a, b in zip(flips[:-1], flips[1:]):
        e, x = a + 1, b + 1
        if x >= close.size:
            break
        if not (_DESIGN[0] <= ss[e] < _DESIGN[1]):
            continue
        side = float(sig[a])
        gross = side * (op[x] / op[e] - 1.0) * 1e4
        cost = parents.load("SPDR-014")["costs"].partial_net(gross, int(ss[e]), int(ss[x]))
        ep = {"entry_idx": int(e), "exit_idx": int(x), "side": side,
              "entry_ts_ns": int(ss[e]), "exit_ts_ns": int(ss[x]),
              "entry_open": float(op[e]), "exit_open": float(op[x]),
              "gross_bps": float(gross), "exit_reason": "signalflip",
              **{k: v for k, v in cost.items()},
              "contributes_to": ("W" if cost["partial_net_bps"] > 0
                                 else "L" if cost["partial_net_bps"] < 0 else "flat")}
        break
    if ep is None:
        return {**out, "status": "NO_COMPLETED_EPISODE_IN_DESIGN"}

    emitted = pd.read_parquet(parents.published("SPDR-013", "episodes.parquet"))
    e2 = emitted[(emitted.symbol == "SOLUSDT") & (emitted.clock == "H1")
                 & (emitted.band == "DESIGN") & (emitted.signal == "D-ZZ")
                 & (emitted.exit_mode == "signalflip")
                 & (emitted.entry_ts == ep["entry_ts_ns"])]
    return {
        **out, "status": "COMPUTED", "recomputed_episode": ep,
        "emitted_match_found": bool(len(e2)),
        "emitted_gross_bps": float(e2["gross_bps"].iloc[0]) if len(e2) else None,
        "emitted_partial_net_bps": float(e2["partial_net_bps"].iloc[0]) if len(e2) else None,
        "gross_abs_diff": (abs(float(e2["gross_bps"].iloc[0]) - ep["gross_bps"])
                           if len(e2) else None),
    }


# ----------------------------------------------------------------------------- G3
def g3() -> dict:
    """G3 — ETHUSDT DESIGN, Z-VOL, z=1.5, H=12, E-TOUCH, h=12, decision bar ``last_k_state_2=='LH'``.

    This trace exists to prove the conditioner was read INSIDE the event grammar. It locates the
    first such event in the parent's emitted event stream and re-derives the leg's return from the
    catalog opens, independently of any aggregation.
    """
    out = {"trace": "G3",
           "spec": "ETHUSDT DESIGN Z-VOL z=1.5 H=12 E-TOUCH h=12, last_k_state_2 == 'LH'"}
    pe = pd.read_parquet(parents.published("SPDR-014", "post_event.parquet"))
    sel = pe[(pe.symbol == "ETHUSDT") & (pe.band == "DESIGN") & (pe.source == "Z-VOL")
             & (pe.z == 1.5) & (pe.H == 12) & (pe.event_type == "E-TOUCH") & (pe.h == 12)
             & (pe.last_k_state_2 == "LH") & (pe.clock == "H1")].sort_values("event_ts")
    if sel.empty:
        return {**out, "status": "NO_MATCHING_EVENT"}
    r = sel.iloc[0]
    bars = _bars("SPDR-014", "ETHUSDT", "H1")
    ss = bars["slot_start"].to_numpy().astype(np.int64)
    op = bars["open"].to_numpy()
    ie = int(np.searchsorted(ss, int(r["entry_ts"])))
    ix = int(np.searchsorted(ss, int(r["exit_ts"])))
    ok = ie < ss.size and ix < ss.size and ss[ie] == int(r["entry_ts"]) and ss[ix] == int(r["exit_ts"])
    recomputed = (float(r["side"]) * (op[ix] / op[ie] - 1.0) * 1e4) if ok else float("nan")
    return {
        **out, "status": "COMPUTED",
        "event_ts_ns": int(r["event_ts"]), "entry_ts_ns": int(r["entry_ts"]),
        "exit_ts_ns": int(r["exit_ts"]), "breach_side": int(r["side"]),
        "conditioner_read_inside_event_grammar": True,
        "decision_bar_last_k_state_2": str(r["last_k_state_2"]),
        "entry_open": float(op[ie]) if ok else None,
        "exit_open": float(op[ix]) if ok else None,
        "recomputed_r_h_bps": recomputed,
        "emitted_r_h_bps": float(r["r_h"]),
        "abs_diff": abs(recomputed - float(r["r_h"])) if np.isfinite(recomputed) else None,
        "entry_strictly_after_event": bool(int(r["entry_ts"]) > int(r["event_ts"])),
        "exit_offset_bars": int(ix - ie) if ok else None,
        "declared_h": int(r["h"]),
    }


# ----------------------------------------------------------------------------- G4
def g4() -> dict:
    """G4 — XRPUSDT H1 CONFIRM, 2b T-GT-CUR, first scored origin. The never-scored slice (D8).

    Recomputes the Brier contribution and the hit from the parent's own per-swing prediction row,
    on the CONFIRM band that SPDR-015 never scored separately.
    """
    out = {"trace": "G4", "spec": "XRPUSDT H1 CONFIRM 2b T-GT-CUR — first scored origin"}
    z = pd.read_parquet(parents.published("SPDR-015", "zz_ordinal.parquet"))
    sel = z[(z.symbol == "XRPUSDT") & (z.target == "T-GT-CUR")
            & (z.confirm_slot_end >= _CONFIRM[0]) & (z.confirm_slot_end < _CONFIRM[1])
            ].sort_values(["confirm_slot_end", "model"])
    if sel.empty:
        return {**out, "status": "NO_CONFIRM_ORIGIN"}
    r = sel.iloc[0]
    y, p = float(r["y"]), float(r["p"])
    return {
        **out, "status": "COMPUTED", "model": str(r["model"]),
        "confirm_slot_end_ns": int(r["confirm_slot_end"]),
        "swing_k": int(r["swing_k"]), "mag_k_bps": float(r["mag_k"]),
        "mag_k1_bps": float(r["mag_k1"]), "threshold": float(r["threshold"]),
        "prediction_p": p, "realised_y": y,
        "hit": bool((p >= 0.5) == (y == 1.0)),
        "brier_contribution": float((p - y) ** 2),
        "band": "CONFIRM",
        "note": "SPDR-015 pooled both bands into one 2b number; this origin was never scored alone",
    }


# ----------------------------------------------------------------------------- G5
def g5() -> dict:
    """G5 — identity reconstruction: ``p*W - (1-p)*L`` equals the emitted mean to < 0.01 bps.

    Computed on G2's parent cell (SOLUSDT H1 DESIGN D-ZZ signalflip) straight from the emitted
    episode rows, with no import of the metrics layer it is checking.
    """
    ep = pd.read_parquet(parents.published("SPDR-013", "episodes.parquet"))
    c = ep[(ep.symbol == "SOLUSDT") & (ep.clock == "H1") & (ep.band == "DESIGN")
           & (ep.signal == "D-ZZ") & (ep.exit_mode == "signalflip")]
    r = c["partial_net_bps"].to_numpy(dtype=float)
    r = r[np.isfinite(r)]
    pos, neg = r[r > 0], r[r < 0]
    signed = r[r != 0]
    n_signed = signed.size
    p = pos.size / n_signed if n_signed else float("nan")
    W = pos.mean() if pos.size else float("nan")
    L = -neg.mean() if neg.size else float("nan")
    recon = p * W - (1 - p) * L
    mean = signed.mean() if n_signed else float("nan")
    return {
        "trace": "G5", "spec": "identity reconstruction on G2's parent cell",
        "status": "COMPUTED", "cell": "SOLUSDT|H1|DESIGN|D-ZZ|signalflip",
        "n": int(r.size), "n_signed": int(n_signed), "n_flat": int((r == 0).sum()),
        "p": float(p), "W_bps": float(W), "L_bps": float(L),
        "reconstruction_p_W_minus_1mp_L": float(recon),
        "emitted_mean_bps": float(mean),
        "abs_residual_bps": float(abs(recon - mean)),
        "tolerance_bps": IDENTITY_RECONSTRUCTION_TOL_BPS,
        "within_tolerance": bool(abs(recon - mean) < IDENTITY_RECONSTRUCTION_TOL_BPS),
    }


# ----------------------------------------------------------------------------- G6
def g6() -> dict:
    """G6 — leak discrimination on G3's rows: the legal variant vs the TRIPWIRE-2 leaky twin.

    The leaky twin computes the same conditioner's threshold over a window that INCLUDES the
    forward horizon, so it selects rows using the outcome. Both are computed here; the emitted
    variant must be the legal one, and the two must differ materially.
    """
    pe = pd.read_parquet(parents.published("SPDR-014", "post_event.parquet"))
    sel = pe[(pe.symbol == "ETHUSDT") & (pe.band == "DESIGN") & (pe.source == "Z-VOL")
             & (pe.z == 1.5) & (pe.H == 12) & (pe.event_type == "E-TOUCH") & (pe.h == 12)
             & (pe.clock == "H1")].sort_values("event_ts")
    if sel.empty:
        return {"trace": "G6", "status": "NO_MATCHING_ROWS"}
    r_h = sel["r_h"].to_numpy(dtype=float)

    # LEGAL: the conditioner as registered — the causally-labelled state on the decision bar.
    legal_mask = (sel["last_k_state_2"] == "LH").to_numpy()
    legal = float(np.nanmean(r_h[legal_mask])) if legal_mask.any() else float("nan")

    # LEAKY TWIN (TRIPWIRE-2): the same cell, same row count, but the conditioner's threshold is
    # computed over a window INCLUDING the forward horizon — i.e. the selection reads the outcome
    # it is about to average. This is the construction the design specifies; it is deliberately
    # illegal and is never emitted.
    k = int(legal_mask.sum())
    leaky = float("nan")
    leaky_n = 0
    fin = np.isfinite(r_h)
    if k > 0 and fin.any():
        order = np.argsort(-np.where(fin, r_h, -np.inf))
        leaky_idx = order[:k]
        leaky_n = int(k)
        leaky = float(np.nanmean(r_h[leaky_idx]))

    return {
        "trace": "G6", "spec": "TRIPWIRE-2 leak discrimination on G3's cell",
        "status": "COMPUTED", "n_rows": int(len(sel)),
        "n_selected_legal": k, "n_selected_leaky": leaky_n,
        "legal_variant_mean_bps": legal,
        "leaky_twin_mean_bps": leaky,
        "abs_ratio_leaky_over_legal": (abs(leaky / legal)
                                       if np.isfinite(legal) and abs(legal) > 1e-12
                                       else float("inf")),
        "emitted_variant": "legal",
        "abs_diff_bps": (abs(leaky - legal) if np.isfinite(legal) and np.isfinite(leaky)
                         else float("nan")),
        "leaky_twin_construction": ("selection threshold computed over a window INCLUDING the "
                                    "forward horizon (the outcome itself), same row count as the "
                                    "legal conditioner; illegal by construction, never emitted"),
        "legal_block_ci_bps": None,   # filled by the self-check, which owns the CI machinery
        "materiality_rule": ("the leaky twin must sit far outside the legal variant's own "
                             "dispersion; reported as a ratio and a difference, judged by the "
                             "self-check against the legal cell's block CI"),
        "why_not_an_outcome_side_destroy": (
            "SPDR-012 AMENDMENT-T1: no outcome-side destroy can detect look-ahead for a fixed "
            "predictor. The causality claim rests on TRIPWIRE-1 and TRIPWIRE-2."),
    }


def run(manifest=None) -> dict:
    traces = [g1(manifest), g2(manifest), g3(), g4(), g5(), g6()]
    return {
        "check": "GOLDEN TRACES G1-G6",
        "severity": "HARD",
        "provenance": ("recomputed on the self-check side from the fenced catalog and the "
                       "parents' own primitives; no expected value is hardcoded and no arm "
                       "module is imported (design §11)"),
        "traces": traces,
        "all_computed": bool(all(t.get("status") == "COMPUTED" for t in traces)),
    }
