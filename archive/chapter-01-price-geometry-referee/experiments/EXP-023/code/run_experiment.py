def _robust_ratio(values: np.ndarray) -> float:
    """Mean / MAD risk-adjusted level (NaN when MAD is ~0); non-parametric."""
    finite = values[np.isfinite(values)]
    if finite.size == 0:
        return math.nan
    mad = float(np.median(np.abs(finite - np.median(finite))))
    if mad <= 0.0:
        return math.nan
    return float(np.mean(finite)) / mad


def _sharpe_diag(values: np.ndarray) -> float:
    """Classic mean/std diagnostic (labeled non-primary; weak for time series)."""
    finite = values[np.isfinite(values)]
    if finite.size < 2:
        return math.nan
    std = float(np.std(finite, ddof=1))
    if std <= 0.0:
        return math.nan
    return float(np.mean(finite)) / std


def _entry_exit_pairs(trades: pl.DataFrame) -> list[tuple[dict[str, Any], dict[str, Any] | None]]:
    """Pair each entry trade with its next exit chronologically (None if unfinished)."""
    if trades.is_empty():
        return []
    order_cols = ["SourceCloseTime", "_file_order"]
    if "TradeSequence" in trades.columns:
        order_cols = ["SourceCloseTime", "TradeSequence", "_file_order"]
    ordered_frame = trades.with_row_index("_file_order").sort(order_cols)
    ordered = ordered_frame.drop("_file_order").to_dicts()
    pairs: list[tuple[dict[str, Any], dict[str, Any] | None]] = []
    open_entry: dict[str, Any] | None = None
    for record in ordered:
        action = str(record["Action"])
        if action.startswith("enter_"):
            open_entry = record
        elif action.startswith("exit_") and open_entry is not None:
            pairs.append((open_entry, record))
            open_entry = None
    if open_entry is not None:
        pairs.append((open_entry, None))
    return pairs


def metric_book_for_cell(cell: CellRun) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """Compute the original AVWAP strategy metric book + event/trade diagnostics."""
    returns, c_pos, _aligned = returns_and_positions(cell.candidate_positions)
    cost = cost_bps_for(cell.instrument, cell.domain)
    active = np.abs(c_pos) > 0.0
    gross_bps = c_pos * returns * 10_000.0
    net_bps = gross_bps - cost * active.astype(float)
    raw_bps = returns * 10_000.0

    trades = cell.candidate_trades
    events = cell.candidate_events
    pairs = _entry_exit_pairs(trades)
    lifetime_bps: list[float] = []
    n_favorable = n_adverse = n_trend = n_unfinished = 0
    for entry, exit_trade in pairs:
        if exit_trade is None:
            n_unfinished += 1
            continue
        direction = 1 if str(entry["Action"]) == "enter_long" else -1
        lifetime_bps.append(
            float(10_000.0 * direction * math.log(float(exit_trade["Price"]) / float(entry["Price"])))
        )
        action = str(exit_trade["Action"])
        n_favorable += action == "exit_favorable"
        n_adverse += action == "exit_adverse"
        n_trend += action == "exit_trend_change"

    n_entries = sum(1 for t in (trades.to_dicts() if not trades.is_empty() else []) if str(t["Action"]).startswith("enter_"))
    n_pyramid_skipped = sum(
        1 for t in (trades.to_dicts() if not trades.is_empty() else []) if str(t["Action"]) == "pyramid_skipped"
    )
    n_bounce = 0 if events.is_empty() else int(events.filter(pl.col("EventType").is_in(["bounce", "bounce_pyramid"])).height)
    n_pyramid_bounce = 0 if events.is_empty() else int(events.filter(pl.col("EventType") == "bounce_pyramid").height)
    n_completed_targets = n_favorable + n_adverse

    lifetime = np.asarray(lifetime_bps, dtype=float)
    metric_row = {
        "instrument": cell.instrument,
        "domain": cell.domain,
        "n_domain_bars": cell.candidate_positions.height,
        "n_return_rows": int(len(returns)),
        "n_bounce_events": n_bounce,
        "n_pyramid_bounce_events": n_pyramid_bounce,
        "bounce_prevalence_per_bar": n_bounce / cell.candidate_positions.height if cell.candidate_positions.height else math.nan,
        "n_entries": n_entries,
        "n_nonexecuted_pyramids": n_pyramid_skipped,
        "n_completed_moves": n_completed_targets,
        "n_favorable": n_favorable,
        "n_adverse": n_adverse,
        "n_trend_change": n_trend,
        "n_unfinished": n_unfinished,
        "successful_bounce_rate": (n_favorable / n_completed_targets) if n_completed_targets else math.nan,
        "trend_change_rate": (n_trend / (n_completed_targets + n_trend)) if (n_completed_targets + n_trend) else math.nan,
        "lifetime_expectancy_bps": float(np.mean(lifetime)) if lifetime.size else math.nan,
        "model_gross_bps": float(np.mean(gross_bps)) if gross_bps.size else math.nan,
        "model_net_bps": float(np.mean(net_bps)) if net_bps.size else math.nan,
        "raw_return_bps": float(np.mean(raw_bps)) if raw_bps.size else math.nan,
        "model_robust_ratio": _robust_ratio(net_bps),
        "raw_robust_ratio": _robust_ratio(raw_bps),
        "model_sharpe_diag": _sharpe_diag(net_bps),
        "raw_sharpe_diag": _sharpe_diag(raw_bps),
        "cost_bps": cost,
    }
    diagnostics = _direction_pyramid_diagnostics(cell, trades, events)
    return metric_row, diagnostics


def validate_metric_book(metric_rows: list[dict[str, Any]], blockers: Blockers) -> None:
    """Fail closed when scoped metric-book gating fields are non-finite.

    The scope gates on finite strategy *expectancy* (``model_net_bps``) and the
    finite *raw-return* risk-adjusted comparison (``raw_return_bps``,
    ``raw_robust_ratio``). ``model_robust_ratio`` is deliberately *not* gated:
    it is mean/MAD over all bars, so a mostly-flat position series (MAD~0) yields
    a null per the scope's zero-baseline rule ("any zero denominator is
    null/non-reportable, never a zero effect"); it stays reported-where-defined
    in the metric book rather than hard-blocking the screen.
    """
    required = ("model_net_bps", "raw_return_bps", "raw_robust_ratio")
    expected = len(INSTRUMENTS) * len(DOMAINS)
    if len(metric_rows) != expected:
        blockers.add(f"metric book has {len(metric_rows)}/{expected} rows")
    for row in metric_rows:
        missing = [field_name for field_name in required if not _is_finite_number(row.get(field_name))]
        if missing:
            blockers.add(f"{row.get('instrument')}/{row.get('domain')}: non-finite metric-book fields {missing}")


def _direction_pyramid_diagnostics(
    cell: CellRun, trades: pl.DataFrame, events: pl.DataFrame
) -> list[dict[str, Any]]:
    """Event/trade counts split by direction and is_pyramid for the cell."""
    rows: list[dict[str, Any]] = []
    # Tag entries with the triggering bounce's is_pyramid via a SourceCloseTime join.
    entries = (
        trades.filter(pl.col("Action").is_in(["enter_long", "enter_short"]))
        if not trades.is_empty()
        else pl.DataFrame()
    )
    pyramid_times: set[Any] = set()
    if not events.is_empty():
        pyramid_times = {
            parse_iso_naive_utc(t)
            for t in events.filter(pl.col("EventType") == "bounce_pyramid").get_column("SourceCloseTime")
        }
    for direction, label in ((1, "long"), (-1, "short")):
        n_bounce = n_pyr_bounce = n_entries = n_pyr_entries = 0
        if not events.is_empty():
            dir_events = events.filter((pl.col("Position") == direction) & pl.col("EventType").is_in(["bounce", "bounce_pyramid"]))
            n_bounce = int(dir_events.height)
            n_pyr_bounce = int(dir_events.filter(pl.col("EventType") == "bounce_pyramid").height)
        if not entries.is_empty():
            action = "enter_long" if direction == 1 else "enter_short"
            dir_entries = entries.filter(pl.col("Action") == action)
            n_entries = int(dir_entries.height)
            n_pyr_entries = sum(
                1 for t in dir_entries.get_column("SourceCloseTime") if parse_iso_naive_utc(t) in pyramid_times
            )
        rows.append(
            {
                "instrument": cell.instrument,
                "domain": cell.domain,
                "direction": label,
                "n_bounce_events": n_bounce,
                "n_pyramid_bounce_events": n_pyr_bounce,
                "n_entries": n_entries,
                "n_pyramid_entries": n_pyr_entries,
            }
        )
    return rows


