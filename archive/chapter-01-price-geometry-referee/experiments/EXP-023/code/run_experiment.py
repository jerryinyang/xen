def _load_presliced_source_frame(path: Path) -> tuple[str, pl.DataFrame]:
    """Load a pre-sliced first-70% time-bar file for C#/Python smoke comparison."""
    columns = ["Symbol", "OpenTime", "CloseTime", "Open", "High", "Low", "Close", "TickVolume"]
    schema = pl.scan_parquet(path).collect_schema().names()
    missing = sorted(set(columns).difference(schema))
    if missing:
        raise ValueError(f"{path.name} missing required smoke columns: {missing}")
    frame = pl.scan_parquet(path).select(columns).sort("CloseTime").collect()
    if frame.is_empty():
        raise ValueError(f"{path.name} has no smoke rows")
    instrument = str(frame.select(pl.first("Symbol")).item()).upper()
    return instrument, frame


