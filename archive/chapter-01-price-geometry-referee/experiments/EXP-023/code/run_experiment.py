    if exp020.exists():
        meta = _read_json(exp020)
        _expect(meta.get("overall_status") == "SUPPORTED_FULL", blockers, rows, "EXP-020 status", str(meta.get("overall_status")))
        _expect(bool(meta.get("invariants_ok")), blockers, rows, "EXP-020 invariants", str(meta.get("invariants_ok")))
