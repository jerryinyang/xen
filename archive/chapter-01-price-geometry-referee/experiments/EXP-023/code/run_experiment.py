"""Experiment EXP-023: AVWAP Baseline Candidate Screen (Phase 004, CF-AVWAP-001/HYP-004).

Implements the analysis plan in ``python/experiments/EXP-023/analysis-plan.md``.

EXP-023 screens the *frozen first-branch* AVWAP baseline signal -- generated by the
cTrader strategy-host branch (``Strategy=AvwapBaseline``) -- through the frozen
Phase 004 qualification suite on emitted real OHLC prices, and reports the original
AVWAP strategy metric book.

Division of labour (binding):
  - **Signal generation is cTrader's** (StrategyHost/AvwapBounceModel.cs +
    DonchianBreakoutModel.cs). This Python harness *ingests and validates only* --
    it never regenerates the AVWAP candidate signal for screening. The only place
    Python runs ``xen.avwap`` is the *transcription smoke* (Step 2), an explicitly
    scoped one-time C#-vs-Python check, not a screening input.
  - The suite is frozen: strict gate stack (EXP-003/005), EXP-012 ratified-loose
    /strict-fallback referee, EXP-018 revised portfolio-fitness unit (vs the
    EXP-019 D-dogfood-book Donchian(20) reference). No thresholds, costs,
    denominators, referee logic, or the reference-book identity are retuned here.

The final 30% global holdout is never loaded, inspected, emitted, or plotted. cTrader
runs are admitted only after the holdout fence (``SourceCloseTime < AnalysisEndUtc``)
is re-asserted on emitted rows.

cTrader runs are generated at the manual execution gate *after* this code is approved,
so when run directories or dependency artifacts are absent the harness fails loudly to
``BLOCKED`` (per scope) rather than crashing or inventing a market verdict.
"""

