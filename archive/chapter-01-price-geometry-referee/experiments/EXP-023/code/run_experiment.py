def build_qualification(
    admitted: list[CellRun],
    standalone_rows: list[dict[str, Any]],
    incremental_rows: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], dict[str, int]]:
    """Per-cell suite pass classification and pass-path tallies."""
    standalone_by = {(r["instrument"], r["domain"]): r for r in standalone_rows}
    incremental_by = {(r["instrument"], r["domain"]): r for r in incremental_rows}
    rows: list[dict[str, Any]] = []
    tally = {"strict": 0, "loose": 0, "incremental": 0, "suite_pass": 0, "reportable": 0}
    for cell in admitted:
        key = (cell.instrument, cell.domain)
        sa = standalone_by.get(key, {})
        inc = incremental_by.get(key, {})
        strict = bool(sa.get("strict_passed", False))
        loose = bool(sa.get("effective_loose_passed", False))
        incremental = bool(inc.get("positive_incremental", False))
        reportable = bool(inc.get("reportable", False)) and bool(sa)
        suite_pass = strict or loose or incremental
        tally["strict"] += strict
        tally["loose"] += loose
        tally["incremental"] += incremental
        tally["suite_pass"] += suite_pass
        tally["reportable"] += reportable
        rows.append(
            {
                "instrument": cell.instrument,
                "domain": cell.domain,
                "reportable": reportable,
                "strict_pass": strict,
                "loose_pass": loose,
                "incremental_pass": incremental,
                "suite_pass": suite_pass,
            }
        )
    return rows, tally


def overall_status(blockers: Blockers, admitted: list[CellRun], tally: dict[str, int], *, expected_cells: int) -> str:
    """Resolve the EXP-023 screen-level conclusion per scope criteria."""
    if blockers.any or len(admitted) != expected_cells:
        return "BLOCKED"
    if tally["reportable"] != expected_cells:
        return "INCONCLUSIVE"
    strict_or_loose = tally["strict"] or tally["loose"]
    incremental = tally["incremental"]
    if strict_or_loose and incremental:
        return "SUPPORTED_MIXED"
    if strict_or_loose:
        return "SUPPORTED_STANDALONE"
    if incremental:
        return "SUPPORTED_INCREMENTAL"
    return "REFUTED"


