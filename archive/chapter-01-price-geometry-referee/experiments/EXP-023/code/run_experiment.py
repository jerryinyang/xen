    incremental_rows: list[dict[str, Any]] = []
    metric_rows: list[dict[str, Any]] = []
    diagnostics_rows: list[dict[str, Any]] = []
    for cell in tqdm(admitted, desc="screen cells", disable=not admitted):
        standalone_rows.append(screen_standalone(cell, settings))
