def _fence_ok(positions: pl.DataFrame, analysis_end: Any) -> tuple[bool, Any]:
    """True iff every emitted SourceCloseTime is strictly before AnalysisEndUtc."""
    if positions.is_empty() or analysis_end is None:
        return positions.is_empty(), None
    max_time = positions.get_column("SourceCloseTime").max()
    return parse_iso_naive_utc(max_time) < parse_iso_naive_utc(analysis_end), max_time


def _expected_domain_minutes(domain: str) -> int:
    """Domain label to cTrader domain-minute parameter."""
    return {"5m": 5, "1h": 60, "4h": 240}[domain]


def _expected_min_coverage(domain: str) -> float | None:
    """Expected cTrader min-coverage parameter for the scoped domain."""
    return None if domain == "5m" else 0.9


def _validate_position_contract(
    positions: pl.DataFrame, *, strategy: str, instrument: str, domain: str
) -> list[str]:
    """Return schema/content contract violations for emitted positions."""
    issues: list[str] = []
    required = {
        "SourceCloseTime",
        "Domain",
        "Strategy",
        "Position",
        "RealOpen",
        "RealHigh",
        "RealLow",
        "RealClose",
    }
    missing = required.difference(positions.columns)
    if missing:
        return [f"positions missing columns {sorted(missing)}"]
    if positions.is_empty():
        return ["positions empty"]

    domains = set(positions.get_column("Domain").unique().to_list())
    strategies = set(positions.get_column("Strategy").unique().to_list())
    if domains != {domain}:
        issues.append(f"position Domain values {sorted(domains)} != {domain}")
    if strategies != {strategy}:
        issues.append(f"position Strategy values {sorted(strategies)} != {strategy}")

    if positions.get_column("SourceCloseTime").n_unique() != positions.height:
        issues.append("duplicate SourceCloseTime rows")
    if not positions.get_column("SourceCloseTime").is_sorted():
        issues.append("SourceCloseTime not sorted")

    bad_positions = positions.filter(~pl.col("Position").is_in([-1, 0, 1])).height
    if bad_positions:
        issues.append(f"{bad_positions} Position rows outside {{-1,0,1}}")

    price_nulls = sum(positions.get_column(col).null_count() for col in ("RealOpen", "RealHigh", "RealLow", "RealClose"))
    if price_nulls:
        issues.append(f"{price_nulls} null real-price values")
    nonfinite = positions.filter(
        ~(
            pl.col("RealOpen").is_finite()
            & pl.col("RealHigh").is_finite()
            & pl.col("RealLow").is_finite()
            & pl.col("RealClose").is_finite()
        )
    ).height
    if nonfinite:
        issues.append(f"{nonfinite} non-finite real-price rows")

    if instrument and "symbol" in positions.columns:
        symbols = set(str(s).upper() for s in positions.get_column("symbol").unique().to_list())
        if symbols and symbols != {instrument}:
            issues.append(f"position symbols {sorted(symbols)} != {instrument}")
    return issues


def _validate_run_metadata(
    metadata: dict[str, Any], *, strategy: str, instrument: str, domain: str
) -> list[str]:
    """Return metadata contract violations for a strategy-host run."""
    issues: list[str] = []
    parameters = metadata.get("parameters", {})
    expected_minutes = _expected_domain_minutes(domain)
    expected_min = _expected_min_coverage(domain)
    expected_strict = expected_min is None

    if str(metadata.get("strategy", "")) != strategy:
        issues.append(f"metadata strategy {metadata.get('strategy')!r} != {strategy!r}")
    if str(metadata.get("symbol", "")).upper() != instrument:
        issues.append(f"metadata symbol {metadata.get('symbol')!r} != {instrument!r}")
    if str(metadata.get("domain", "")) != domain:
        issues.append(f"metadata domain {metadata.get('domain')!r} != {domain!r}")
    if metadata.get("analysis_end_utc") is None:
        issues.append("metadata missing analysis_end_utc")
    if _safe_int(parameters.get("domain_minutes")) != expected_minutes:
        issues.append(f"domain_minutes {parameters.get('domain_minutes')!r} != {expected_minutes}")
    if bool(parameters.get("strict_coverage")) != expected_strict:
        issues.append(f"strict_coverage {parameters.get('strict_coverage')!r} != {expected_strict}")
    observed_min = parameters.get("min_coverage")
    if expected_min is None:
        if observed_min is not None:
            issues.append(f"min_coverage {observed_min!r} should be null for strict 5m")
    elif not _float_close(_safe_float(observed_min), expected_min):
        issues.append(f"min_coverage {observed_min!r} != {expected_min}")

    if strategy == CANDIDATE_STRATEGY:
        if _safe_int(parameters.get("fast_ma")) != 20 or _safe_int(parameters.get("slow_ma")) != 50:
            issues.append(f"AVWAP MA params invalid: {parameters}")
        if not _float_close(_safe_float(parameters.get("volume_exponent")), 0.75):
            issues.append(f"volume_exponent {parameters.get('volume_exponent')!r} != 0.75")
        if not _float_close(_safe_float(parameters.get("band_multiplier")), 1.0):
            issues.append(f"band_multiplier {parameters.get('band_multiplier')!r} != 1.0")
    elif strategy == REFERENCE_STRATEGY:
        if _safe_int(parameters.get("lookback")) != 20:
            issues.append(f"Donchian lookback {parameters.get('lookback')!r} != 20")
    return issues


def _same_feed_check(candidate: pl.DataFrame, reference: pl.DataFrame) -> dict[str, Any]:
    """Check candidate and reference carry identical timestamps and real OHLC."""
    result: dict[str, Any] = {
        "same_feed_ok": False,
        "n_time_mismatch": math.nan,
        "feed_max_abs_diff": math.nan,
    }
    if candidate.height != reference.height:
        result["n_time_mismatch"] = abs(candidate.height - reference.height)
        return result

    cand_times = candidate.get_column("SourceCloseTime").to_list()
    ref_times = reference.get_column("SourceCloseTime").to_list()
    mismatches = sum(1 for a, b in zip(cand_times, ref_times, strict=True) if parse_iso_naive_utc(a) != parse_iso_naive_utc(b))
    result["n_time_mismatch"] = mismatches
    if mismatches:
        return result

    max_diff = 0.0
    for column in ("RealOpen", "RealHigh", "RealLow", "RealClose"):
        left = candidate.get_column(column).to_numpy().astype(float)
        right = reference.get_column(column).to_numpy().astype(float)
        diffs = np.abs(left - right)
        max_diff = max(max_diff, float(np.max(diffs)) if diffs.size else 0.0)
        if not np.allclose(left, right, rtol=FEED_PRICE_REL_TOL, atol=FEED_PRICE_ABS_TOL, equal_nan=False):
            result["feed_max_abs_diff"] = max_diff
            return result
    result["same_feed_ok"] = True
    result["feed_max_abs_diff"] = max_diff
    return result


def admit_runs(
    blockers: Blockers,
) -> tuple[list[CellRun], list[dict[str, Any]], list[dict[str, Any]]]:
    """Discover, validate, and holdout-fence cTrader runs for all 12 cells."""
    admitted: list[CellRun] = []
    run_rows: list[dict[str, Any]] = []
    fence_rows: list[dict[str, Any]] = []

    for instrument in INSTRUMENTS:
        for domain in DOMAINS:
            cand_dir = discover_run(CANDIDATE_STRATEGY, instrument, domain)
            ref_dir = discover_run(REFERENCE_STRATEGY, instrument, domain)
            row: dict[str, Any] = {
                "instrument": instrument,
                "domain": domain,
                "candidate_run": str(cand_dir) if cand_dir else "",
                "reference_run": str(ref_dir) if ref_dir else "",
                "candidate_rows": 0,
                "reference_rows": 0,
                "same_feed_ok": False,
                "n_time_mismatch": math.nan,
                "feed_max_abs_diff": math.nan,
                "admitted": False,
                "reason": "",
            }
            if cand_dir is None or ref_dir is None:
                row["reason"] = "missing candidate and/or reference run directory"
                blockers.add(f"{instrument}/{domain}: missing candidate and/or reference run directory")
                run_rows.append(row)
                continue

            try:
                cand_run = load_emitted_run(cand_dir)
                ref_run = load_emitted_run(ref_dir)
            except (FileNotFoundError, ValueError) as exc:
                row["reason"] = f"load error: {exc}"
                blockers.add(f"{instrument}/{domain}: emitted run load error: {exc}")
                run_rows.append(row)
                continue

            cand_pos = cand_run.positions.sort("SourceCloseTime")
            ref_pos = ref_run.positions.sort("SourceCloseTime")
            analysis_end = parse_iso_naive_utc(cand_run.metadata.get("analysis_end_utc"))
            row["candidate_rows"] = cand_pos.height
            row["reference_rows"] = ref_pos.height

            issues = (
                _validate_run_metadata(cand_run.metadata, strategy=CANDIDATE_STRATEGY, instrument=instrument, domain=domain)
                + _validate_run_metadata(ref_run.metadata, strategy=REFERENCE_STRATEGY, instrument=instrument, domain=domain)
                + _validate_position_contract(cand_pos, strategy=CANDIDATE_STRATEGY, instrument=instrument, domain=domain)
                + _validate_position_contract(ref_pos, strategy=REFERENCE_STRATEGY, instrument=instrument, domain=domain)
            )
            ref_analysis_end = parse_iso_naive_utc(ref_run.metadata.get("analysis_end_utc"))
            if analysis_end != ref_analysis_end:
                issues.append(f"candidate/reference analysis_end_utc mismatch: {analysis_end} != {ref_analysis_end}")

            cand_fence_ok, cand_max = _fence_ok(cand_pos, analysis_end)
            ref_fence_ok, ref_max = _fence_ok(ref_pos, analysis_end)
            feed_check = _same_feed_check(cand_pos, ref_pos)
            row.update(feed_check)
            fence_rows.append(
                {
                    "instrument": instrument,
                    "domain": domain,
                    "analysis_end_utc": str(analysis_end),
                    "candidate_max_source_close": str(cand_max),
                    "reference_max_source_close": str(ref_max),
                    "candidate_fence_ok": cand_fence_ok,
                    "reference_fence_ok": ref_fence_ok,
                }
            )

            if cand_pos.is_empty() or ref_pos.is_empty():
                row["reason"] = "empty candidate or reference positions"
                blockers.add(f"{instrument}/{domain}: empty candidate or reference positions")
            elif analysis_end is None:
                row["reason"] = "candidate run_metadata missing analysis_end_utc"
                blockers.add(f"{instrument}/{domain}: candidate run_metadata missing analysis_end_utc")
            elif issues:
                row["reason"] = "; ".join(issues)
                blockers.add(f"{instrument}/{domain}: run contract violation: {row['reason']}")
            elif not (cand_fence_ok and ref_fence_ok):
                row["reason"] = "holdout fence violation"
                blockers.add(f"{instrument}/{domain}: holdout fence violation in emitted run")
            elif not feed_check["same_feed_ok"]:
                row["reason"] = "candidate/reference same-feed OHLC mismatch"
                blockers.add(f"{instrument}/{domain}: candidate/reference same-feed OHLC mismatch")
            else:
                row["admitted"] = True
                admitted.append(
                    CellRun(
                        instrument=instrument,
                        domain=domain,
                        candidate_dir=cand_dir,
                        reference_dir=ref_dir,
                        candidate_positions=cand_pos,
                        candidate_events=read_optional_parquet(cand_dir / "events.parquet"),
                        candidate_trades=read_optional_parquet(cand_dir / "trade_blotter.parquet"),
                        reference_positions=ref_pos,
                        analysis_end_utc=analysis_end,
                    )
                )
            run_rows.append(row)

    _assert_admission_floor(admitted, blockers)
    return admitted, run_rows, fence_rows


def _assert_admission_floor(admitted: list[CellRun], blockers: Blockers) -> None:
    """Fail closed unless all scoped cTrader cells are admitted."""
    expected = len(INSTRUMENTS) * len(DOMAINS)
    if len(admitted) != expected:
        blockers.add(f"only {len(admitted)}/{expected} scoped cTrader cells admitted")
    for domain in DOMAINS:
        n = len({c.instrument for c in admitted if c.domain == domain})
        if n != len(INSTRUMENTS):
            blockers.add(f"domain {domain}: only {n}/4 instruments admitted")


