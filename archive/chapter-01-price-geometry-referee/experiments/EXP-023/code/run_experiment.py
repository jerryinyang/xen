def _events_by_trigger(frame: pl.DataFrame) -> dict[Any, dict[str, Any]]:
    """Index event rows by ``trigger_time`` for a tolerance comparison."""
    if frame.is_empty() or "trigger_time" not in frame.columns:
        return {}
    out: dict[Any, dict[str, Any]] = {}
    for record in frame.iter_rows(named=True):
        out[parse_iso_naive_utc(record["trigger_time"])] = record
    return out


def _close(a: float, b: float) -> bool:
    """Absolute-or-relative float closeness for the transcription smoke."""
    if a is None or b is None or (isinstance(a, float) and math.isnan(a)) or (isinstance(b, float) and math.isnan(b)):
        return a == b
    return abs(a - b) <= max(SMOKE_ABS_TOL, SMOKE_REL_TOL * max(abs(a), abs(b)))


def run_avwap_smoke(blockers: Blockers) -> list[dict[str, Any]]:
    """Compare the C# parity AVWAP events against the xen.avwap reference per domain.

    This is the scoped transcription check: it loads the same fixed source Parquet
    (first-70% analysis slice), generates reference events with ``xen.avwap``, and
    compares trigger timing and frozen band/target prices to the C# parity export.
    It is *not* a screening input -- screening never regenerates the signal.
    """
    rows: list[dict[str, Any]] = []
    parity_dir = discover_parity_export()
    if parity_dir is None:
        rows.append({"domain": "ALL", "status": "PENDING", "reason": "no parity export found"})
        blockers.add("C# AVWAP transcription smoke PENDING: no parity export found")
        return rows
    meta_path = parity_dir / "export_metadata.json"
    if not meta_path.exists():
        rows.append({"domain": "ALL", "status": "PENDING", "reason": "parity export_metadata.json missing"})
        blockers.add("C# AVWAP transcription smoke PENDING: export_metadata.json missing")
        return rows

    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    source_path = Path(str(meta.get("input_path", "")))
    if not source_path.is_absolute():
        source_path = PROJECT_ROOT / source_path
    if not source_path.exists():
        rows.append({"domain": "ALL", "status": "PENDING", "reason": f"source parquet missing: {source_path}"})
        blockers.add(f"C# AVWAP transcription smoke PENDING: source parquet missing: {source_path}")
        return rows
    if not _is_analysis_slice_path(source_path):
        reason = f"source parquet is not explicitly labelled as first-70% analysis input: {source_path.name}"
        rows.append({"domain": "ALL", "status": "FAIL", "reason": reason})
        blockers.add(f"C# AVWAP transcription smoke FAILED: {reason}")
        return rows

    instrument, source_frame = _load_presliced_source_frame(source_path)
    domain_frames = build_domain_frames(source_frame)
    for domain in DOMAINS:
        csv_path = parity_dir / f"avwap_baseline_events_{domain}.csv"
        if not csv_path.exists():
            rows.append({"domain": domain, "status": "PENDING", "reason": "parity events csv missing"})
            blockers.add(f"C# AVWAP transcription smoke PENDING for {domain}: parity events csv missing")
            continue
        cs_events = _events_by_trigger(pl.read_csv(csv_path, infer_schema_length=10000))
        result = generate_avwap_events(domain_frames[domain], instrument=instrument, domain=domain)
        py_events = _events_by_trigger(result.events)
        rows.append(_compare_smoke_cell(domain, py_events, cs_events))

    if any(r.get("status") == "FAIL" for r in rows):
        blockers.add("C# AVWAP transcription smoke FAILED for at least one domain")
    if any(r.get("status") == "PENDING" for r in rows):
        blockers.add("C# AVWAP transcription smoke PENDING for at least one domain")
    return rows


def _compare_smoke_cell(
    domain: str, py_events: dict[Any, dict[str, Any]], cs_events: dict[Any, dict[str, Any]]
) -> dict[str, Any]:
    """Compare one domain's Python vs C# AVWAP events; return a smoke row."""
    fields = (
        "avwap_at_trigger",
        "band_spread_at_trigger",
        "favorable_target_at_trigger",
        "adverse_target_at_trigger",
        "anchor_price",
    )
    common = set(py_events) & set(cs_events)
    field_mismatch = 0
    max_abs_diff = 0.0
    for key in common:
        for column in fields:
            a = float(py_events[key][column])
            b = float(cs_events[key][column])
            if not _close(a, b):
                field_mismatch += 1
            if not (math.isnan(a) or math.isnan(b)):
                max_abs_diff = max(max_abs_diff, abs(a - b))
    counts_match = len(py_events) == len(cs_events) == len(common)
    status = "PASS" if counts_match and field_mismatch == 0 else "FAIL"
    return {
        "domain": domain,
        "status": status,
        "n_python_events": len(py_events),
        "n_csharp_events": len(cs_events),
        "n_matched_trigger_time": len(common),
        "n_field_mismatch": field_mismatch,
        "max_abs_price_diff": max_abs_diff,
        "reason": "" if status == "PASS" else "event count or band/target mismatch",
    }


