def discover_run(strategy: str, instrument: str, domain: str) -> Path | None:
    """Return the latest strategy-host run dir for a (strategy, instrument, domain).

    Matches the ``StrategyRunParquetWriter`` naming
    ``<strategy>_<symbol>_<domain>_<yyyyMMdd_HHmmss>`` (lower-cased symbol). The
    timestamp suffix sorts lexically, so the last match is the most recent.
    """
    if not STRATEGY_RUNS_DIR.exists():
        return None
    prefix = f"{strategy}_{instrument.lower()}_{domain}_"
    matches = sorted(p for p in STRATEGY_RUNS_DIR.glob(f"{prefix}*") if p.is_dir())
    return matches[-1] if matches else None


