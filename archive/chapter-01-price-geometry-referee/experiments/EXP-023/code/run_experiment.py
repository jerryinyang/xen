def plot_suite_verdict_matrix(qualification: list[dict[str, Any]], path: Path) -> None:
    """Instrument x domain matrix coloured by qualification path."""
    if not qualification:
        _blocked_plot(path, "Suite verdict matrix", "BLOCKED: no admitted cells")
        return
    code = {"none": 0, "incremental": 1, "loose": 2, "strict": 3}
    grid = np.full((len(INSTRUMENTS), len(DOMAINS)), np.nan)
    by = {(r["instrument"], r["domain"]): r for r in qualification}
    for i, inst in enumerate(INSTRUMENTS):
        for j, dom in enumerate(DOMAINS):
            r = by.get((inst, dom))
            if r is None:
                continue
            if r["strict_pass"]:
                grid[i, j] = code["strict"]
            elif r["loose_pass"]:
                grid[i, j] = code["loose"]
            elif r["incremental_pass"]:
                grid[i, j] = code["incremental"]
            else:
                grid[i, j] = code["none"]
    sns.set_theme(style="white")
    fig, ax = plt.subplots(figsize=(7, 5))
    ax.imshow(grid, cmap="YlGn", vmin=0, vmax=3, aspect="auto")
    ax.set_xticks(range(len(DOMAINS)), DOMAINS)
    ax.set_yticks(range(len(INSTRUMENTS)), INSTRUMENTS)
    for i in range(len(INSTRUMENTS)):
        for j in range(len(DOMAINS)):
            val = grid[i, j]
            label = "—" if math.isnan(val) else {0: "none", 1: "incr", 2: "loose", 3: "strict"}[int(val)]
            ax.text(j, i, label, ha="center", va="center", fontsize=9)
    ax.set_title("EXP-023 suite qualification path by cell")
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def plot_effect_forest(standalone_rows: list[dict[str, Any]], incremental_rows: list[dict[str, Any]], path: Path) -> None:
    """Standalone and incremental effects with CIs against frozen detection floors."""
    if not standalone_rows and not incremental_rows:
        _blocked_plot(path, "Effect forest", "BLOCKED: no admitted cells")
        return
    standalone_by = {(r["instrument"], r["domain"]): r for r in standalone_rows}
    incremental_by = {(r["instrument"], r["domain"]): r for r in incremental_rows}
    ordered_keys = [(inst, dom) for inst in INSTRUMENTS for dom in DOMAINS if (inst, dom) in standalone_by or (inst, dom) in incremental_by]
    sns.set_theme(style="whitegrid")
    fig, ax = plt.subplots(figsize=(9, max(4, 0.45 * len(ordered_keys))))
    labels = [f"{inst}/{dom}" for inst, dom in ordered_keys]
    legend_seen: set[str] = set()

    def _label(name: str) -> str:
        if name in legend_seen:
            return "_nolegend_"
        legend_seen.add(name)
        return name

    for k, key in enumerate(ordered_keys):
        sa = standalone_by.get(key)
        if sa:
            y = k - 0.11
            ax.plot([sa["ci_lower_bps"], sa["ci_upper_bps"]], [y, y], color="steelblue", label=_label("standalone CI"))
            ax.plot(sa["effect_bps"], y, "o", color="navy", label=_label("standalone effect"))
            ax.plot(sa["strict_mde_bps"], y, "|", color="firebrick", markersize=12, label=_label("strict MDE"))
            ax.plot(sa["loose_mde_bps"], y, "|", color="darkorange", markersize=12, label=_label("loose MDE"))
        inc = incremental_by.get(key)
        if inc and inc.get("reportable"):
            y = k + 0.11
            ax.plot(
                [inc["incremental_ci_lower_bps"], inc["incremental_ci_upper_bps"]],
                [y, y],
                color="mediumseagreen",
                label=_label("incremental CI"),
            )
            ax.plot(inc["incremental_edge_bps"], y, "s", color="darkgreen", label=_label("incremental effect"))
            ax.plot(inc["incremental_mde_bps"], y, "|", color="purple", markersize=12, label=_label("incremental MDE"))
    ax.axvline(0.0, color="grey", linestyle="--", linewidth=0.8)
    ax.set_yticks(range(len(labels)), labels)
    ax.set_xlabel("net effect / incremental edge (bps)")
    ax.set_title("EXP-023 effect forest vs frozen detection floors")
    ax.legend(fontsize=7, loc="best")
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def plot_model_vs_raw(admitted: list[CellRun], path: Path) -> None:
    """Cumulative model-net vs raw real-return by domain (bounded instrument panels)."""
    if not admitted:
        _blocked_plot(path, "Model vs raw cumulative returns", "BLOCKED: no admitted cells")
        return
    sns.set_theme(style="whitegrid")
    fig, axes = plt.subplots(1, len(DOMAINS), figsize=(4 * len(DOMAINS), 4), squeeze=False)
    for j, domain in enumerate(DOMAINS):
        ax = axes[0][j]
        for cell in (c for c in admitted if c.domain == domain):
            returns, c_pos, _ = returns_and_positions(cell.candidate_positions)
            cost = cost_bps_for(cell.instrument, cell.domain)
            net = c_pos * returns * 10_000.0 - cost * (np.abs(c_pos) > 0).astype(float)
            raw = returns * 10_000.0
            ax.plot(np.cumsum(net), label=f"{cell.instrument} model", linewidth=1.0)
            ax.plot(np.cumsum(raw), label=f"{cell.instrument} raw", linewidth=0.9, linestyle="--")
        ax.axhline(0.0, color="grey", linestyle="--", linewidth=0.7)
        ax.set_title(f"{domain} cumulative model net vs raw (bps)")
        ax.set_xlabel("return row")
        ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


