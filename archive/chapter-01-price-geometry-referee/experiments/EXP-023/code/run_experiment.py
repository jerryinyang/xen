# Step 3: standalone frozen-suite screen (strict + ratified-loose/fallback)
# --------------------------------------------------------------------------- #
def screen_standalone(cell: CellRun, settings: SuiteSettings) -> dict[str, Any]:
    """Strict gate + EXP-012 ratified-loose/strict-fallback verdict for one cell.

    Reuses the VAL-002 ``screen_emitted_run`` path (frozen referee, 70/30 row split
    on the emitted analysis set). The loose verdict re-derives L5 at the EXP-012
    adopted tau on the SAME gate core (legs L1-L4 unchanged), exactly as EXP-006/007
    /011/012 derived L5 endpoints; it falls back to strict if tau is not looser.
    """
    seed = seed_for("EXP-004", cell.instrument, cell.domain, CANDIDATE_STRATEGY)
    referee_rows = screen_emitted_positions(
        cell.candidate_positions,
        instrument=cell.instrument,
        domain=cell.domain,
        seed=seed,
        train_end_utc=None,
        alpha_values=(ALPHA0,),
        n_bootstrap=N_BOOTSTRAP,
    )
    gate = next(r for r in referee_rows if r["referee"] == "gate_stack")
    legs = json.loads(gate["leg_results"])
    materiality = float(legs["materiality_bps"])
    ci_lower = float(gate["ci_lower_bps"])
    strict_passed = bool(gate["passed"])

    legs_1_4 = all(legs[k] for k in ("L1_readiness", "L2_integrity", "L3_outcome", "L4_stability"))
    tau = settings.loose_tau_bps.get(cell.domain, math.nan)
    fallback_engaged = not (math.isfinite(tau) and tau <= materiality)
    if math.isfinite(tau):
        loose_l5 = ci_lower > tau
        loose_passed = bool(legs_1_4 and loose_l5)
    else:
        loose_passed = False
    effective_loose_passed = bool(loose_passed or strict_passed)  # never stricter than strict

    return {
        "instrument": cell.instrument,
        "domain": cell.domain,
        "strategy": CANDIDATE_STRATEGY,
        "effect_bps": float(gate["effect_bps"]),
        "ci_lower_bps": ci_lower,
        "ci_upper_bps": float(gate["ci_upper_bps"]),
        "effective_n": float(gate["effective_n"]),
        "block_length": int(gate["block_length"]),
        "materiality_bps": materiality,
        "strict_mde_bps": settings.strict_mde_bps.get(cell.domain, math.nan),
        "loose_tau_bps": tau,
        "loose_mde_bps": settings.loose_mde_bps.get(cell.domain, math.nan),
        "strict_passed": strict_passed,
        "loose_passed": loose_passed,
        "effective_loose_passed": effective_loose_passed,
        "loose_fallback_engaged": fallback_engaged,
        "leg_results": gate["leg_results"],
    }


