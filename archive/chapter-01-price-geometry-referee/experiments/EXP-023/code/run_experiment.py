def plot_risk_adjusted_heatmap(metric_rows: list[dict[str, Any]], path: Path) -> None:
    """Model vs raw mean/std (Sharpe diagnostic) level by instrument/domain.

    The primary robust mean/MAD ratio is undefined on the model side for the
    mostly-flat AVWAP position series (MAD~0), so the scoped model-vs-raw
    risk-adjusted comparison is drawn from the finite mean/std diagnostic pair
    (``model_sharpe_diag`` vs ``raw_sharpe_diag``).
    """
    if not metric_rows:
        _blocked_plot(path, "Risk-adjusted heatmap", "BLOCKED: no admitted cells")
        return
    by = {(r["instrument"], r["domain"]): r for r in metric_rows}
    diff = np.full((len(INSTRUMENTS), len(DOMAINS)), np.nan)
    for i, inst in enumerate(INSTRUMENTS):
        for j, dom in enumerate(DOMAINS):
            r = by.get((inst, dom))
            if r is None:
                continue
            model = r["model_sharpe_diag"]
            raw = r["raw_sharpe_diag"]
            if isinstance(model, float) and isinstance(raw, float) and math.isfinite(model) and math.isfinite(raw):
                diff[i, j] = model - raw
    sns.set_theme(style="white")
    fig, ax = plt.subplots(figsize=(7, 5))
    vmax = np.nanmax(np.abs(diff)) if np.isfinite(diff).any() else 1.0
    im = ax.imshow(diff, cmap="RdBu", vmin=-vmax, vmax=vmax, aspect="auto")
    ax.set_xticks(range(len(DOMAINS)), DOMAINS)
    ax.set_yticks(range(len(INSTRUMENTS)), INSTRUMENTS)
    for i in range(len(INSTRUMENTS)):
        for j in range(len(DOMAINS)):
            if math.isfinite(diff[i, j]):
                ax.text(j, i, f"{diff[i, j]:.2f}", ha="center", va="center", fontsize=8)
    fig.colorbar(im, ax=ax, label="model − raw mean/std (Sharpe diagnostic) level")
    ax.set_title(
        "EXP-023 risk-adjusted level: model − raw mean/std\n"
        "(robust mean/MAD ratio undefined for sparse position series)"
    )
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


