#!/usr/bin/env python3
"""EXP-025 (CF-HTFDI-001/HYP-A) conf generator — design §5/§6/§15.

Deterministic: per-symbol ANALYSIS_END = the 70%-row CloseTime of the NEWEST
timebars file per symbol (the pipeline's analysis cutoff); BACKTEST_END = one
minute past it (dd/MM/yyyy HH:mm). Regenerable byte-identically (QA checks).

Stages (subcommands):
  t1        20 confs EXP-025-t1-x{X}-h{H}.conf — X in {2,3,4,5,8} x H in {12,24,36,48},
            all 22 symbols, gate=di, exit=e0.                                (440 runs)
  controls  EXP-025-ref.conf (gate=state, per-bar HTF-state emission for the
            CTRL-REF-RANDOM analysis-side seed-2001 sampling — model D4) and
            EXP-025-sent.conf (gate=adx sentinel, X=3 H=24 — operator-resolved).  (44 runs)
  t2        post-T1: --cells SYMBOL:X[,SYMBOL:X...] --exits e1,e2,...
            one conf per (exit) covering the survivor cells.
  battery   post-T1: --cells SYMBOL:X:EXIT:H[,...] — 25 confs per cell,
            seeds 1001-1025 (pre-registered, design §6).
  shift     post-T1: --cells SYMBOL:X:EXIT:H[,...] — +60-bar HTF phase-shift
            tripwire arm at the read vehicles.

Usage: python3 gen_exp025_confs.py t1|controls|t2|battery|shift [--cells ...] [--exits ...]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import polars as pl

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
DATA = ROOT / "data" / "timebars"

SYMBOLS = [
    "EURUSD", "GBPUSD", "USDJPY", "USDCHF", "USDCAD", "AUDUSD", "NZDUSD",
    "EURJPY", "GBPJPY", "AUDJPY",
    "USTEC", "US500", "US2000", "JP225", "AUS200", "US30", "STOXX50", "DE40",
    "HK50", "UK100",
    "XAUUSD", "BTCUSD",
]
X_GRID = [2, 3, 4, 5, 8]
H_GRID = [12, 24, 36, 48]
BATTERY_SEEDS = list(range(1001, 1026))
STRATEGY_VALUE = "9"  # XenStrategy.HtfDiBreakout ordinal (Xen.cs enum)


def newest_file(symbol: str) -> Path:
    # canonical admitted set = the 20210602 5-year files (VAL-005 / VAL-007;
    # dataset-reference.md "INFR-003 5-year" row) — never the 2023-vintage files
    cands = sorted(DATA.glob(f"timebars_{symbol.lower()}_20210602_*.parquet"))
    cands = [c for c in cands if "analysis70" not in c.name]
    if not cands:
        raise SystemExit(f"no canonical 20210602 timebars file for {symbol}")
    return cands[-1]


def cutoff_for(symbol: str) -> str:
    df = pl.scan_parquet(newest_file(symbol)).select("CloseTime").collect().sort("CloseTime")
    ts = df[int(df.height * 0.7), "CloseTime"]
    return ts.strftime("%Y-%m-%dT%H:%M:%SZ")


def backtest_end(analysis_end: str) -> str:
    from datetime import datetime, timedelta
    dt = datetime.strptime(analysis_end, "%Y-%m-%dT%H:%M:%SZ") + timedelta(minutes=1)
    return dt.strftime("%d/%m/%Y %H:%M")


def write_conf(name: str, strategy: str, symbols: list[str], model_args: list[str],
               cutoffs: dict[str, str], mode: int = 0) -> None:
    lines = [
        f"# generated by gen_exp025_confs.py — do not hand-edit (regenerate instead)",
        f'STRATEGY="{strategy}"',
        f'STRATEGY_VALUE="{STRATEGY_VALUE}"',
        f"MODE={mode}",
        "",
        f"SYMBOLS=({' '.join(symbols)})",
        "DOMAINS=(5m)",
        "",
        "ANALYSIS_END=(",
    ]
    lines += [f'  [{s}]="{cutoffs[s]}"' for s in symbols]
    lines += [")", "BACKTEST_END=("]
    lines += [f'  [{s}]="{backtest_end(cutoffs[s])}"' for s in symbols]
    lines += [")", "", f"MODEL_ARGS=({' '.join(model_args)})", ""]
    path = HERE / f"{name}.conf"
    path.write_text("\n".join(lines))
    print(f"wrote {path.name} ({len(symbols)} symbols)")


def strategy_name(x: int, exit_: str, gate: str, hold: int = 0, seed: int = 0, shift: int = 0) -> str:
    exit_tag = f"e0h{hold}" if exit_ == "e0" else exit_
    gate_tag = {"di": "di", "adx": "adx", "state": "state"}.get(gate, f"bat{seed}")
    return f"htfdi_x{x}_{exit_tag}_{gate_tag}" + (f"_shift{shift}" if shift else "")


def parse_cells(raw: str, parts: int) -> list[list[str]]:
    cells = [c.split(":") for c in raw.split(",") if c]
    for c in cells:
        if len(c) != parts:
            raise SystemExit(f"bad --cells token {':'.join(c)} (need {parts} ':'-fields)")
    return cells


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("stage", choices=["t1", "controls", "t2", "battery", "shift"])
    ap.add_argument("--cells", default="", help="t2: SYM:X,... | battery/shift: SYM:X:EXIT:H,...")
    ap.add_argument("--exits", default="e1,e2,e3,e4,e5,e6", help="t2 exit list")
    args = ap.parse_args()

    cutoffs = {s: cutoff_for(s) for s in SYMBOLS}
    for s, c in cutoffs.items():
        print(f"  {s}: analysis_end={c}", file=sys.stderr)

    if args.stage == "t1":
        for x in X_GRID:
            for h in H_GRID:
                write_conf(f"EXP-025-t1-x{x}-h{h}", strategy_name(x, "e0", "di", h), SYMBOLS,
                           [f"--HtfX={x}", f"--HtfHold={h}", "--HtfExit=e0", "--HtfGate=di"],
                           cutoffs)
    elif args.stage == "controls":
        write_conf("EXP-025-ref", strategy_name(3, "e0", "state", 24), SYMBOLS,
                   ["--HtfX=3", "--HtfHold=24", "--HtfExit=e0", "--HtfGate=state"], cutoffs)
        write_conf("EXP-025-sent", strategy_name(3, "e0", "adx", 24), SYMBOLS,
                   ["--HtfX=3", "--HtfHold=24", "--HtfExit=e0", "--HtfGate=adx"], cutoffs)
    elif args.stage == "t2":
        cells = parse_cells(args.cells, 2)
        if not cells:
            raise SystemExit("t2 requires --cells SYMBOL:X[,SYMBOL:X...]")
        for exit_ in [e.strip() for e in args.exits.split(",") if e.strip()]:
            native = exit_ in ("e1", "e4")
            for sym, x in cells:
                write_conf(f"EXP-025-t2-{exit_}-{sym.lower()}-x{x}",
                           strategy_name(int(x), exit_, "di"),
                           [sym],
                           [f"--HtfX={x}", "--HtfHold=24", f"--HtfExit={exit_}", "--HtfGate=di"],
                           cutoffs, mode=3 if native else 0)
    elif args.stage == "battery":
        for sym, x, exit_, h in parse_cells(args.cells, 4):
            for seed in BATTERY_SEEDS:
                write_conf(f"EXP-025-bat{seed}-{sym.lower()}-x{x}-{exit_}-h{h}",
                           strategy_name(int(x), exit_, "battery", int(h), seed),
                           [sym],
                           [f"--HtfX={x}", f"--HtfHold={h}", f"--HtfExit={exit_}",
                            "--HtfGate=battery", f"--HtfBatterySeed={seed}"],
                           cutoffs)
    elif args.stage == "shift":
        for sym, x, exit_, h in parse_cells(args.cells, 4):
            native = exit_ in ("e1", "e4")
            write_conf(f"EXP-025-shift-{sym.lower()}-x{x}-{exit_}-h{h}",
                       strategy_name(int(x), exit_, "di", int(h), shift=60),
                       [sym],
                       [f"--HtfX={x}", f"--HtfHold={h}", f"--HtfExit={exit_}",
                        "--HtfGate=di", "--HtfShiftBars=60"],
                       cutoffs, mode=3 if native else 0)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
